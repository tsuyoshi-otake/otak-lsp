/**
 * 文字が地名用漢字かどうかを判定
 */
export function isChimeiKanji(char: string): boolean {
  return CHIMEI_KANJI_SET.has(char);
}

/**
 * 文字が地名の旧字体かどうかを判定
 */
export function isChimeiKyujitai(char: string): boolean {
  return CHIMEI_KYUJITAI_MAP.has(char);
}

/**
 * 地名の旧字体から新字体を取得
 */
export function getChimeiShinjitai(kyujitai: string): string | undefined {
  return CHIMEI_KYUJITAI_MAP.get(kyujitai);
}

/**
 * テキストが有名な地名にマッチするかを判定
 * @param text 検査対象のテキスト
 * @param position 検査する位置
 * @returns マッチした場合はtrue
 */
export function matchesFamousPlaceName(text: string, position: number): boolean {
  for (const placeName of FAMOUS_PLACE_NAMES) {
    const idx = text.indexOf(placeName);
    if (idx >= 0 && idx <= position && position < idx + placeName.length) {
      return true;
    }
  }
  return false;
}

/**
 * テキストが地名パターンにマッチするかを判定
 * @param text 検査対象のテキスト
 * @param position 検査する位置
 * @returns 地名として判定された場合はtrue
 */
export function isLikelyPlaceName(text: string, position: number): boolean {
  // 有名な地名にマッチするか
  if (matchesFamousPlaceName(text, position)) {
    return true;
  }

  // 地名の接尾辞が後に続くかチェック
  const searchEnd = Math.min(position + 15, text.length);
  const subsequentText = text.substring(position, searchEnd);

  for (const suffix of CHIMEI_SUFFIX_PATTERNS) {
    // 1-8文字の地名 + 接尾辞のパターン
    const pattern = new RegExp(`^.{0,8}${suffix}`);
    if (pattern.test(subsequentText)) {
      return true;
    }
  }

  // 住所表記パターン（〇〇県、〇〇市など）
  const addressPattern = /^.{1,4}(都|道|府|県|市|区|町|村|郡)/;
  if (addressPattern.test(subsequentText)) {
    return true;
  }

  return false;
}

/**
 * 住所文字列かどうかを判定
 * 「〒」や「住所」「所在地」などのキーワードで判定
 */
export function isAddressContext(text: string, position: number): boolean {
  // 前方100文字以内に住所関連キーワードがあるか
  const searchStart = Math.max(0, position - 100);
  const precedingText = text.substring(searchStart, position);

  const addressKeywords = [
    '〒', '住所', '所在地', '居所', '本籍', '現住所',
    '送付先', '届出先', '連絡先', '勤務先', '配送先', '届け先',
  ];

  for (const keyword of addressKeywords) {
    if (precedingText.includes(keyword)) {
      return true;
    }
  }

  return false;
}
