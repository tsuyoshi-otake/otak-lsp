/**
 * 指定された文字が常用漢字かどうかを判定する
 * @param char 判定する文字（1文字）
 * @returns 常用漢字の場合はtrue、それ以外はfalse
 */
export function isJouyouKanji(char: string): boolean {
  if (char.length !== 1) {
    return false;
  }
  return JOUYOU_KANJI_SET.has(char);
}

/**
 * 指定された文字が漢字かどうかを判定する
 * CJK統合漢字の範囲をチェック
 * @param char 判定する文字（1文字）
 * @returns 漢字の場合はtrue、それ以外はfalse
 */
export function isKanji(char: string): boolean {
  if (char.length !== 1) {
    return false;
  }
  const code = char.charCodeAt(0);
  // CJK統合漢字: U+4E00-U+9FFF
  // CJK統合漢字拡張A: U+3400-U+4DBF
  // CJK互換漢字: U+F900-U+FAFF
  return (
    (code >= 0x4E00 && code <= 0x9FFF) ||
    (code >= 0x3400 && code <= 0x4DBF) ||
    (code >= 0xF900 && code <= 0xFAFF)
  );
}

/**
 * 常用漢字外の漢字に対する代替提案を取得する
 * @param kanji 常用漢字外の漢字
 * @returns 代替提案（存在しない場合はundefined）
 */
export function getAlternative(kanji: string): NonJouyouAlternative | undefined {
  return NON_JOUYOU_ALTERNATIVES.get(kanji);
}
