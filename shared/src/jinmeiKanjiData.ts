export function isJinmeiKanji(char: string): boolean {
  return JINMEI_KANJI_SET.has(char);
}

/**
 * 文字が旧字体かどうかを判定
 */
export function isKyujitai(char: string): boolean {
  return KYUJITAI_TO_SHINJITAI.has(char);
}

/**
 * 旧字体から新字体を取得
 */
